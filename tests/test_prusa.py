from pathlib import Path

import pytest

from conftest import write_cube_stl
from print3d.blender import BlenderError, find_blender
from print3d.paths import prusa_profiles_dir
from print3d.pipeline import run_job
from print3d.printability import analyze_slice
from print3d.project import inspect_project
from print3d.prusa import (
    PrusaError,
    PrusaRequest,
    build_project_command,
    build_slice_command,
    find_prusa,
    load_bed_mm,
    load_presets,
)

BINARY = Path("/Applications/PrusaSlicer.app/Contents/MacOS/PrusaSlicer")

# Shape of a PrusaSlicer gcode: moves first, stats as comments in the footer.
GCODE = """; generated by PrusaSlicer
M83
G1 Z0.2 F720
G1 X10 Y10 E2.0
G1 X20 Y10 E2.0
G1 Z0.4
G1 X10 Y10 E1.5
; filament used [mm] = 5.50
; filament used [g] = 0.02
; total filament used [g] = 0.02
; total filament used for wipe tower [g] = 0.00
; estimated printing time (normal mode) = 1d 2h 3m 30s
; prusaslicer_config = begin
; layer_height = 0.2
; prusaslicer_config = end
"""


def _request(tmp_path: Path) -> PrusaRequest:
    return PrusaRequest(
        input_mesh=tmp_path / "cube.stl",
        output_gcode=tmp_path / "slice" / "cube.gcode",
        output_project_3mf=tmp_path / "slice" / "cube.3mf",
        presets=load_presets(prusa_profiles_dir() / "presets.json"),
        datadir=tmp_path / "prusa-datadir",
    )


def test_slice_command_uses_presets_and_text_gcode(tmp_path: Path):
    command = build_slice_command(BINARY, _request(tmp_path))
    assert command[command.index("--printer-profile") + 1] == "Prusa CORE One 0.4 HF"
    assert command[command.index("--datadir") + 1] == str((tmp_path / "prusa-datadir").resolve())
    assert "--export-gcode" in command
    assert "--no-binary-gcode" in command
    assert command[command.index("--output") + 1].endswith("cube.gcode")
    assert command[-1].endswith("cube.stl")


def test_project_command_exports_3mf_only(tmp_path: Path):
    command = build_project_command(BINARY, _request(tmp_path))
    assert "--export-3mf" in command
    assert "--export-gcode" not in command
    assert command[command.index("--output") + 1].endswith("cube.3mf")


def test_presets_must_name_all_three(tmp_path: Path):
    path = tmp_path / "presets.json"
    path.write_text('{"printer": "Prusa CORE One 0.4 HF"}')
    with pytest.raises(PrusaError, match="print, filament"):
        load_presets(path)


def test_bed_is_pinned_beside_the_presets(tmp_path: Path):
    assert load_bed_mm(prusa_profiles_dir() / "presets.json") == (250.0, 220.0, 270.0)
    path = tmp_path / "presets.json"
    path.write_text('{"bed_mm": [250, 220]}')
    with pytest.raises(PrusaError, match="bed_mm"):
        load_bed_mm(path)


def test_part_deeper_than_the_coreone_bed_fails(tmp_path: Path, monkeypatch):
    from print3d.dfm import DfmError

    monkeypatch.setenv("PRINT3D_SLICER", "prusa")
    monkeypatch.setenv("PRINT3D_FITS", str(tmp_path / "fits.json"))
    # Fits the X2D's 256 mm, not the CORE One's 220 mm depth.
    stl = write_cube_stl(tmp_path / "cube.stl", 230.0)
    with pytest.raises(DfmError, match="exceeds the bed"):
        run_job("deep cube", mesh=stl, jobs_dir=tmp_path / "jobs", execute=False)


def test_footer_stats_and_layers(tmp_path: Path):
    gcode = tmp_path / "part.gcode"
    gcode.write_text(GCODE)
    metrics = analyze_slice(gcode)
    assert metrics["estimated_minutes"] == pytest.approx(1563.5)
    assert metrics["filament_g"] == 0.02
    assert metrics["printed_layers"] == 2
    assert metrics["total_extruded_mm"] == pytest.approx(5.5)
    plate = inspect_project(gcode)["plates"][0]
    assert plate["estimated_time"] == "1d 2h 3m 30s"
    assert plate["filament_g"] == 0.02
    assert plate["filament_mm"] == "5.50"
    assert plate["png_path"] is None


def _installed() -> bool:
    try:
        find_prusa()
    except PrusaError:
        return False
    return True


def _blender() -> bool:
    try:
        find_blender()
    except BlenderError:
        return False
    return True


@pytest.mark.skipif(not _installed() or not _blender(), reason="PrusaSlicer or Blender is not installed")
def test_cube_slices_with_prusaslicer(tmp_path: Path, cube_stl: Path, monkeypatch):
    monkeypatch.setenv("PRINT3D_SLICER", "prusa")
    monkeypatch.setenv("PRINT3D_FITS", str(tmp_path / "fits.json"))
    report = run_job("prusa cube", mesh=cube_stl, jobs_dir=tmp_path / "jobs")
    assert report["status"] == "ready_for_review"
    assert report["open_in_studio"].endswith("prusa_cube.3mf")
    assert Path(report["open_in_studio"]).is_file()
    assert report["slice_metrics"]["printed_layers"] == 100
    assert report["slice_metrics"]["filament_g"] > 0
    assert report["slice_metrics"]["estimated_minutes"] > 0
    assert "PrusaSlicer" in report["next_step"]
    assert Path(report["plate_png"]).is_file()


@pytest.mark.skipif(not _installed(), reason="PrusaSlicer is not installed")
def test_plate_png_is_none_without_blender(tmp_path: Path, cube_stl: Path, monkeypatch):
    monkeypatch.setenv("PRINT3D_SLICER", "prusa")
    monkeypatch.setenv("PRINT3D_FITS", str(tmp_path / "fits.json"))
    monkeypatch.setenv("BLENDER_BIN", str(tmp_path / "no-blender"))
    monkeypatch.setattr("print3d.blender.BLENDER_LOCATIONS", [])
    monkeypatch.setenv("PATH", "")
    report = run_job("prusa cube", mesh=cube_stl, jobs_dir=tmp_path / "jobs")
    assert report["status"] == "ready_for_review"
    assert report["plate_png"] is None
